CREATE DATABASE MANICURE_AGENDA;

USE MANICURE_AGENDA;

-- TABELA DE CLIENTES
CREATE TABLE CLIENTE(
	ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255) NOT NULL,
    TELEFONE VARCHAR(20),
    EMAIL VARCHAR(255)
);

-- TABELA DE PROFISSIONAIS (MANICURE / PEDICURE)
CREATE TABLE PROFISSIONAL(
	ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(255) NOT NULL,
    ESPECIALIDADE VARCHAR(100) NOT NULL -- Ex: Manicure, Pedicure ou Ambos
);

-- TABELA DE SERVIÇOS
CREATE TABLE SERVICO(
	ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    DESCRICAO VARCHAR(255) NOT NULL,
    DURACAO_MINUTOS INT NOT NULL,
    VALOR DECIMAL(4,2) NOT NULL
);

-- TABELA DE AGENDAMENTOS
CREATE TABLE AGENDAMENTO(
	ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ID_CLIENTE INT NOT NULL,
    ID_PROFISSIONAL INT NOT NULL,
    ID_SERVICO INT NOT NULL,
    DATA_HORA DATETIME NOT NULL,
    STATUS VARCHAR(50) NOT NULL, -- Ex: Agendado, Cancelado, Concluído
    
    CONSTRAINT FK_AGENDAMENTO_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTE(ID),
        
    CONSTRAINT FK_AGENDAMENTO_PROFISSIONAL
        FOREIGN KEY (ID_PROFISSIONAL)
        REFERENCES PROFISSIONAL(ID),
        
    CONSTRAINT FK_AGENDAMENTO_SERVICO
        FOREIGN KEY (ID_SERVICO)
        REFERENCES SERVICO(ID)
);

-- CRIANDO ÍNDICES PARA MELHOR PERFORMANCE
CREATE INDEX IDX_AGENDAMENTO_DATA_HORA
ON AGENDAMENTO (DATA_HORA);

CREATE INDEX IDX_AGENDAMENTO_STATUS
ON AGENDAMENTO (STATUS);

CREATE INDEX IDX_AGENDAMENTO_PROFISSIONAL
ON AGENDAMENTO (ID_PROFISSIONAL);